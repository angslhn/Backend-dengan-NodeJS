// Operator Aritmatika dan Penugasan


//  == Operator Aritmatika ==
// 1. Tambah == + ==
const hasilTambah = 5 + 4
console.log('Hasil Tambah = ' + hasilTambah)

// 2. Kurang == + ==
const hasilKurang = 10 - 2
console.log('Hasil Kurang = ' + hasilKurang)

// 3. Kali == * ==
const hasilKali = 3 * 5
console.log('Hasil Kali = ' + hasilKali)

// 4. Bagi == / ==
const hasilBagi = 15 / 5
console.log('Hasil Bagi = ' + hasilBagi)

// 5. Sisa Bagi == % ==
const hasilSisaBagi = 15 % 5
console.log('Hasil Sisa Bagi = ' + hasilSisaBagi)

// 6. Pangkat == ** ==
const hasilPangkat = 5 ** 5
console.log('Hasil Pangkat = ' + hasilPangkat)

// 7. Penambahan (icrement) == ++ ==
let hasilPenambahan = 10
hasilPenambahan++
console.log('Hasil Penambahan = ' + hasilPenambahan)

// 8. Pengurangan (decrement) == -- ==
let hasilPengurangan = 10
hasilPengurangan--
console.log('Hasil Pengurangan = ' + hasilPengurangan)


// == Operator Penugasan ==
// 1. Mengisi Nilai
const a = 30
console.log('Nilai a adalah = ' + a)

// 2. Tambah dengan nilai baru
let b = 30
b += 10
console.log('Nilai b adalah = ' + b)

// 3. Kurang dengan nilai baru
let c = 30
c -= 10
console.log('Nilai c adalah = ' + b)

// 4. Kali dengan nilai baru
let d = 30
d *= 10
console.log('Nilai d adalah = ' + d)

// 5. Bagi dengan nilai baru
let e = 30
e /= 10
console.log('Nilai e adalah = ' + e)

// 6. Pangkat dengan nilai baru
let f = 30
f **= 10
console.log('Nilai f adalah = ' + f)