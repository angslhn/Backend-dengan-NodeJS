// Operator Aritmatika dan Penugasan

//  == Operator Aritmatika ==
// Tambah == + ==
const addResult = 5 + 4;
console.log("Hasil Tambah = " + addResult);

// Kurang == - ==
const minusResult = 10 - 2;
console.log("Hasil Kurang = " + minusResult);

// Kali == * ==
const multiplyResult = 3 * 5;
console.log("Hasil Kali = " + multiplyResult);

// Bagi == / ==
const divisionResult = 15 / 5;
console.log("Hasil Bagi = " + divisionResult);

// Sisa Bagi == % ==
const modulusResult = 15 % 5;
console.log("Hasil Sisa Bagi = " + modulusResult);

// Pangkat == ** ==
const exponentialResult = 5 ** 5;
console.log("Hasil Pangkat = " + exponentialResult);

